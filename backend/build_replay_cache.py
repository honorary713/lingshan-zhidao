def main():
    before = count()
    print(f"已有缓存条数: {before}")
    ok, fail = 0, 0
    for i, q in enumerate(QUESTIONS, 1):
        try:
            res = run(q, session_id="seed")
            ans = res.get("answer", "")
            if ans and "Mock" not in ans and "离线演示" not in ans:
                ok += 1
                print(f"[{i:02d}/{len(QUESTIONS)}] ✓ {q[:24]} -> {len(ans)}字")
            else:
                fail += 1
                print(f"[{i:02d}/{len(QUESTIONS)}] ✗ 未生成有效回答: {q}")
        except Exception as e:
            fail += 1
            print(f"[{i:02d}/{len(QUESTIONS)}] ✗ 异常: {q} | {e!r}")
    after = count()
    print(f"\n完成：成功 {ok}，失败 {fail}，新增缓存 {after - before}，总计 {after}")


if __name__ == "__main__":
    main()
